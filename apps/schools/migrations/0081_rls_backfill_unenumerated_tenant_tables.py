"""Backfill RLS on every tenant-scoped table the per-app migrations never enumerated.

WHY THIS EXISTS
---------------
Each app's ``*_enable_rls_postgresql.py`` hard-codes a literal ``TABLES = [...]``
frozen at authoring time, and nothing ever adds later tables to it. A model given
a ``school`` FK AFTER its app's RLS migration is therefore never enabled -- while
the app still has both RLS files, so the app-level file-pairing gate stays green.
``scripts/scan_rls_table_coverage.py`` measured 112 such tables across 19 apps.
Two more (``portal_communityforumcategory``, ``portal_communityforumtopic``) are
invisible to that scanner entirely: it walks the runtime app registry, and those
models live in ``apps/portal/models_forums.py``, imported lazily by a view rather
than at ``django.setup()``. This migration is derived from MIGRATION STATE, which
does not depend on import order -- see ``scripts/generate_rls_backfill_tables.py``.

Under single-schema deployment (``USE_DJANGO_TENANTS=False``) RLS *is* the tenant
isolation, so an unenumerated table has none at all. Under schema-per-tenant this
is a no-op (``should_apply_rls`` returns False) because isolation comes from the
schema instead -- see ``apps/schools/rls.py``.

WHY THE LIST IS LITERAL AND NOT DERIVED AT RUN TIME
---------------------------------------------------
Deriving the list from the model registry inside the migration would be
self-maintaining but would defeat ``scripts/scan_rls_table_coverage.py``, which is
a static AST scan for table-name literals in ``*rls*`` migrations. A registry walk
leaves that gate reporting gaps forever while nothing actionable changes -- the
exact "gate that cannot fail" pattern this program exists to remove. The list is
therefore explicit and regenerated by ``scripts/generate_rls_backfill_tables.py``,
so the static gate keeps biting when a new tenant-scoped model lands without RLS.

Proxy models are collapsed by ``db_table``.
"""

