RISK_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3}


def _summarize(workflows: list[dict[str, Any]]) -> dict[str, Any]:
    status_counter: Counter[str] = Counter()
    audience_counter: Counter[str] = Counter()
    surface_counter: Counter[str] = Counter()
    risk_counter: Counter[str] = Counter()
    measurement_counter: Counter[str] = Counter()

    for wf in workflows:
        status_counter[wf["current_status"]] += 1
        surface_counter[wf["surface"]] += 1
        risk_counter[wf["risk_level"]] += 1
        measurement_counter[wf["measurement_status"]] += 1
        for aud in wf["audience"]:
            audience_counter[aud] += 1

    return {
        "by_status": dict(sorted(status_counter.items(), key=lambda x: -x[1])),
        "by_audience": dict(sorted(audience_counter.items(), key=lambda x: -x[1])),
        "by_surface": dict(sorted(surface_counter.items(), key=lambda x: -x[1])),
        "by_risk_level": dict(sorted(risk_counter.items(), key=lambda x: -x[1])),
        "by_measurement_status": dict(sorted(measurement_counter.items(), key=lambda x: -x[1])),
    }


def _sort_for_md(workflows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return sorted(
        workflows,
        key=lambda w: (
            RISK_ORDER.get(w["risk_level"], 99),
            w["current_status"],
            w["workflow_id"],
        ),
    )


def _top10_fix_me_first(workflows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    candidates = [
        w
        for w in workflows
        if w["current_status"]
        in {
            "broken",
            "fragmented",
            "too_many_clicks",
            "missing_how_to",
            "missing_info_tags",
            "missing_ai_help",
            "usable_but_unclear",
        }
        and w["current_status"] != "external_blocked"
    ]
    ranked = sorted(
        candidates,
        key=lambda w: (
            RISK_ORDER.get(w["risk_level"], 99),
            0 if w["current_status"] in {"broken", "fragmented", "too_many_clicks"} else 1,
            w["workflow_id"],
        ),
    )
    return ranked[:10]


def _externally_blocked(workflows: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [w for w in workflows if w["current_status"] == "external_blocked"]


def _build_md(workflows: list[dict[str, Any]], summary: dict[str, Any]) -> str:
    lines: list[str] = []
    lines.append("# Platform workflow classification matrix (Phase 1)")
    lines.append("")
    lines.append(
        "Hand-curated classification of every primary workflow on the platform. "
        "Step counts are flagged `measurement_status: hypothesis` unless explicitly "
        "measured. Decision rules per the Phase 1 brief: `strong` -> preserve, "
        "`usable_but_unclear` -> simplify copy/tags/next-actions, `fragmented` -> "
        "consolidate or guided path, `broken` -> fix end-to-end, `missing_how_to` -> "
        "create how-to metadata, `missing_info_tags` -> add contextual tags, "
        "`missing_ai_help` -> add AI only where specific next action, "
        "`external_blocked` -> document honestly."
    )
    lines.append("")
    lines.append(f"Total workflows classified: **{len(workflows)}**")
    lines.append("")

    lines.append("## Summary tables")
    lines.append("")
    lines.append("### Workflows per status")
    lines.append("")
    lines.append("| Status | Count |")
    lines.append("|---|---:|")
    for status, count in summary["by_status"].items():
        lines.append(f"| `{status}` | {count} |")
    lines.append("")

    lines.append("### Workflows per audience (a workflow may serve more than one)")
    lines.append("")
    lines.append("| Audience | Count |")
    lines.append("|---|---:|")
    for aud, count in summary["by_audience"].items():
        lines.append(f"| `{aud}` | {count} |")
    lines.append("")

    lines.append("### Workflows per surface")
    lines.append("")
    lines.append("| Surface | Count |")
    lines.append("|---|---:|")
    for surface, count in summary["by_surface"].items():
        lines.append(f"| `{surface}` | {count} |")
    lines.append("")

    lines.append("### Workflows per risk level")
    lines.append("")
    lines.append("| Risk level | Count |")
    lines.append("|---|---:|")
    for risk, count in summary["by_risk_level"].items():
        lines.append(f"| `{risk}` | {count} |")
    lines.append("")

    lines.append("### Workflows per measurement status")
    lines.append("")
    lines.append("| Measurement status | Count |")
    lines.append("|---|---:|")
    for ms, count in summary["by_measurement_status"].items():
        lines.append(f"| `{ms}` | {count} |")
    lines.append("")

    lines.append("## Top-10 fix-me-first list")
    lines.append("")
    lines.append(
        "Ranked by risk (descending) then status priority (broken/fragmented/"
        "too_many_clicks first). `external_blocked` rows are excluded — they are "
        "listed separately below."
    )
    lines.append("")
    lines.append("| # | Workflow ID | Risk | Status | Rationale |")
    lines.append("|---:|---|---|---|---|")
    for i, wf in enumerate(_top10_fix_me_first(workflows), start=1):
        rationale = wf["required_fix"]
        lines.append(
            f"| {i} | `{wf['workflow_id']}` | `{wf['risk_level']}` | "
            f"`{wf['current_status']}` | {rationale} |"
        )
    lines.append("")

    blocked = _externally_blocked(workflows)
    lines.append("## Externally blocked workflows")
    lines.append("")
    if not blocked:
        lines.append("_None — every classified workflow is either solvable in-repo or already strong._")
    else:
        lines.append(
            "These cannot be fixed by in-repo Phase 4 work alone; they are gated on "
            "an actor or system outside this repo. Each row quotes the blocker verbatim "
            "from the `required_fix` field so it is auditable."
        )
        lines.append("")
        lines.append("| Workflow ID | Blocker (quoted) |")
        lines.append("|---|---|")
        for wf in blocked:
            lines.append(f"| `{wf['workflow_id']}` | {wf['required_fix']} |")
    lines.append("")

    lines.append("## Full per-workflow table")
    lines.append("")
    lines.append(
        "Sorted by `risk_level` descending then `current_status`. `current_step_count` "
        "is a hypothesis estimate range unless `measurement_status: measured` is set."
    )
    lines.append("")
    lines.append(
        "| Workflow ID | App | Audience | Surface | Entry route | Primary goal | "
        "Current steps | Ideal | Status | Risk | Required fix | Measurement |"
    )
    lines.append("|---|---|---|---|---|---|---|---:|---|---|---|---|")
    for wf in _sort_for_md(workflows):
        audience_csv = ",".join(wf["audience"])
        # MD-escape pipe characters defensively
        primary_goal = wf["primary_goal"].replace("|", "\\|")
        required_fix = wf["required_fix"].replace("|", "\\|")
        entry_route = wf["entry_route"].replace("|", "\\|")
        lines.append(
            f"| `{wf['workflow_id']}` | `{wf['app']}` | {audience_csv} | "
            f"`{wf['surface']}` | `{entry_route}` | {primary_goal} | "
            f"{wf['current_step_count']} | {wf['ideal_step_count']} | "
            f"`{wf['current_status']}` | `{wf['risk_level']}` | {required_fix} | "
            f"`{wf['measurement_status']}` |"
        )
    lines.append("")

    return "\n".join(lines) + "\n"


