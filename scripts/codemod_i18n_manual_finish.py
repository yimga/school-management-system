def main() -> int:
    changed = 0
    for rel, old, new in REPLACEMENTS:
        path = REPO / rel
        if not path.is_file():
            print("MISSING", rel)
            continue
        text = path.read_text(encoding="utf-8")
        if old not in text:
            continue
        path.write_text(text.replace(old, new, 1), encoding="utf-8")
        changed += 1
        print("OK", rel)
    print(f"Applied {changed} replacements")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
